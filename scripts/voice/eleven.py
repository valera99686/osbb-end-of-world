"""Voices the game's lines with Eleven v4 through mage.space.

Run it with the Python of the mage-studio engine (Playwright and a stealth browser
must be installed there), after `npm test` and `node scripts/voice/export-lines.cjs --eleven`:

    MAGE_STUDIO_DIR=<engine folder> <engine python> scripts/voice/eleven.py
        [--lines scripts/voice/lines-eleven.json] [--only galyna,intercom]
        [--limit 3] [--force] [--shard 0/3] [--new-accounts]

The engine drives mage.space the way a person does: one browser, the Eleven v4
model picked once, the voice and its stability set per speaker (eleven-voices.json),
each line typed in and the finished MP3 saved. A line costs 30 gems. When the balance of the
account does not cover one more line the run stops (the state is saved, run it again
later); only with --new-accounts does it open a fresh free account (300 gems, ten
lines) and go on, which is the person's own decision to make. Every MP3 is
trimmed, shaped (`fx` of the speaker), levelled and written to public/voice/<id>.ogg
(Opus, mono), replacing an OmniVoice recording of the same line; lib/game/voice-manifest.ts
lists the ids that exist. spoken-eleven.json remembers which text each recording was
made from, so a changed text is spoken again and an interrupted run goes on where it stopped.
"""
from __future__ import annotations

import argparse
import json
import logging
import os
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
STUDIO = os.environ.get("MAGE_STUDIO_DIR", "")
if not STUDIO or not Path(STUDIO, "mage_studio").is_dir():
    sys.exit("Set MAGE_STUDIO_DIR to the folder of the mage-studio engine (it holds mage_studio/).")
sys.path.insert(0, STUDIO)
from mage_studio import engine as eng  # noqa: E402

MODEL = "Eleven v4"
BITRATE = "24k"
LINE_TIMEOUT = 240
TRIM = (
    "silenceremove=start_periods=1:start_threshold=-48dB:start_silence=0.04,"
    "areverse,silenceremove=start_periods=1:start_threshold=-48dB:start_silence=0.12,areverse"
)
LOUDNESS = "loudnorm=I=-18:TP=-1.5:LRA=9"


def log(message: str) -> None:
    print(message, flush=True)


def encode(source: Path, target: Path, fx: str | None) -> None:
    chain = ",".join(part for part in (TRIM, fx, LOUDNESS) if part)
    temp = target.with_suffix(".tmp.ogg")
    subprocess.run(
        ["ffmpeg", "-y", "-loglevel", "error", "-i", str(source), "-af", chain, "-ac", "1",
         "-c:a", "libopus", "-b:a", BITRATE, "-application", "voip", str(temp)],
        check=True,
    )
    os.replace(temp, target)


def write_manifest(out_dir: Path) -> int:
    ids = sorted(path.stem for path in out_dir.glob("*.ogg") if not path.stem.endswith(".tmp"))
    body = ",\n  ".join(f"'{i}'" for i in ids)
    manifest = ROOT / "lib" / "game" / "voice-manifest.ts"
    manifest.write_text(
        "// Generated by scripts/voice/generate.py or eleven.py: the voiced lines that have a file in public/voice.\n"
        f"export const VOICE_IDS: ReadonlySet<string> = new Set([\n  {body},\n]);\n",
        encoding="utf-8",
    )
    return len(ids)


class OutOfGems(Exception):
    """The account cannot pay for another line and new accounts were not allowed."""


class Studio:
    """One browser on mage.space with the Eleven v4 model chosen."""

    def __init__(self, new_accounts: bool = False) -> None:
        self.new_accounts = new_accounts
        self.ctx = None
        self.page = None
        self.voice = ""
        self.stability = -1.0
        self.accounts = 0

    def open(self) -> bool:
        self.close()
        sess = eng.load_session()
        udd = os.path.join(eng.PROFILE_ROOT, "voice_" + sess["localId"][:12])
        os.makedirs(udd, exist_ok=True)
        self.ctx = eng.open_context(udd, headless=eng.browser_mode() == "headless")
        page = self.ctx.pages[0] if self.ctx.pages else self.ctx.new_page()
        page.set_default_timeout(20000)
        self.ctx.add_init_script(
            eng.INIT_JS.replace("__APIKEY__", eng.KEY).replace("__APP__", eng.APP)
            .replace("__USER__", json.dumps(eng.fb_user(sess))))
        page.goto(eng.SITE + "/advanced", wait_until="domcontentloaded", timeout=60000)
        self.page = page
        if not eng.wait_logged_in(page):
            log("the session did not come up")
            return False
        eng.dismiss_overlays(page, tries=2)
        eng.close_prompt_help(page)
        eng.ensure_content_settings(page, sess)
        eng.clear_attachments(page)
        return self.pick_model()

    def pick_model(self) -> bool:
        message, picked = eng.select_model(self.page, MODEL)
        if eng.VARIANT_MISSING in message or not picked:
            log(f"model not picked: {message}")
            return False
        arch, tags = eng.current_arch(self.page, picked)
        if "AUDIO" not in tags:
            log(f"the active model «{arch}» does not make sound")
            return False
        self.voice, self.stability = "", -1.0
        return True

    def close(self) -> None:
        try:
            if self.ctx:
                self.ctx.close()
        except Exception:
            pass
        self.ctx = self.page = None

    def ensure_gems(self) -> bool:
        """A fresh account when the balance does not cover one more line."""
        price = eng.read_price(self.page)
        gems = eng.read_gems_wait(self.page, timeout=20, want_positive=False)
        if not price or gems is None or price <= gems:
            return True
        if not self.new_accounts:
            raise OutOfGems(f"gems {gems}, a line costs {price}")
        log(f"gems {gems}, price {price}: a new account")
        try:
            sess = eng.create_account()
        except Exception as exc:
            log(f"no new account: {exc}")
            return False
        if not eng.switch_account(self.page, sess):
            return False
        self.accounts += 1
        eng.ensure_content_settings(self.page, sess)
        return self.pick_model()

    def set_voice(self, voice: str, stability: float) -> None:
        if voice != self.voice:
            eng.set_named_controls(self.page, {"Voice": voice})
            self.voice = voice
        if abs(stability - self.stability) > 1e-6:
            eng.set_named_controls(self.page, {"Stability": stability})
            self.stability = stability

    def speak(self, voice: str, stability: float, text: str, out: Path) -> bool:
        if not self.ensure_gems():
            return False
        self.set_voice(voice, stability)
        before = eng.visible_audio(self.page)
        comp = eng.composer(self.page)
        if comp is None or not eng.submit_prompt(self.page, comp, text):
            return False
        deadline = time.time() + LINE_TIMEOUT
        src = None
        while time.time() < deadline:
            time.sleep(3)
            fresh = eng.visible_audio(self.page) - before
            if fresh:
                src = sorted(fresh)[0]
                break
        if not src:
            return False
        return bool(eng.save_image(self.ctx, self.page, src, str(out)))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--lines", type=Path, default=HERE / "lines-eleven.json")
    parser.add_argument("--voices", type=Path, default=HERE / "eleven-voices.json")
    parser.add_argument("--out", type=Path, default=ROOT / "public" / "voice")
    parser.add_argument("--spoken", type=Path, default=HERE / "spoken-eleven.json",
                        help="id -> the text each recording was made from; a changed text is spoken again")
    parser.add_argument("--work", type=Path, default=HERE / "refs" / "eleven",
                        help="where the raw MP3 files go (kept: a change to fx or loudness re-encodes them)")
    parser.add_argument("--only", default="", help="comma-separated speakers")
    parser.add_argument("--limit", type=int, default=0, help="at most this many lines per speaker")
    parser.add_argument("--force", action="store_true", help="speak lines again even if they are recorded")
    parser.add_argument("--new-accounts", action="store_true",
                        help="when the gems run out, open a fresh free account and go on (off: the run stops)")
    parser.add_argument("--shard", default="", help="i/n: this process speaks every n-th line only")
    parser.add_argument("--reencode", action="store_true",
                        help="no synthesis: run the raw MP3 files in --work through the filters again")
    args = parser.parse_args()
    logging.basicConfig(level=logging.WARNING, format="%(message)s")

    voices = json.loads(args.voices.read_text(encoding="utf-8"))
    lines = json.loads(args.lines.read_text(encoding="utf-8"))
    only = {k for k in args.only.split(",") if k}
    args.out.mkdir(parents=True, exist_ok=True)
    args.work.mkdir(parents=True, exist_ok=True)
    made = json.loads(args.spoken.read_text(encoding="utf-8")) if args.spoken.exists() else {}

    def remember() -> None:
        args.spoken.write_text(json.dumps(made, ensure_ascii=False, indent=1, sort_keys=True) + "\n", encoding="utf-8")

    if args.reencode:
        count = 0
        for line in lines:
            raw = args.work / f"{line['id']}.mp3"
            if (only and line["key"] not in only) or not raw.exists():
                continue
            encode(raw, args.out / f"{line['id']}.ogg", voices[line["key"]].get("fx"))
            count += 1
        log(f"re-encoded {count} lines; {write_manifest(args.out)} files in {args.out}")
        return

    part, total = (int(x) for x in args.shard.split("/")) if args.shard else (0, 1)
    todo, counts = [], {}
    for index, line in enumerate(lines):
        key = line["key"]
        if key not in voices or (only and key not in only) or index % total != part:
            continue
        if args.limit and counts.get(key, 0) >= args.limit:
            continue
        counts[key] = counts.get(key, 0) + 1
        if not args.force and (args.out / f"{line['id']}.ogg").exists() and made.get(line["id"]) == line["speech"]:
            continue
        todo.append(line)
    todo.sort(key=lambda l: l["key"])  # one voice at a time: fewer settings to change
    log(f"{len(todo)} lines to speak of {len(lines)}")

    studio = Studio(args.new_accounts)
    done = failed = streak = restarts = 0
    begin = time.time()
    try:
        if todo and not studio.open():
            sys.exit("could not open mage.space")
        for line in todo:
            cfg = voices[line["key"]]
            raw = args.work / f"{line['id']}.mp3"
            ok = False
            for attempt in range(3):
                try:
                    if raw.exists():
                        raw.unlink()
                    ok = studio.speak(cfg["voice"], cfg["stability"], line["speech"], raw)
                except OutOfGems as exc:
                    log(f"stopped: {exc}")
                    raise
                except Exception as exc:  # a browser hiccup must not stop the batch
                    log(f"  error: {type(exc).__name__}: {str(exc)[:120]}")
                if ok:
                    break
                log(f"  retry {attempt + 1} for {line['id']}")
                time.sleep(5)
            if ok:
                encode(raw, args.out / f"{line['id']}.ogg", cfg.get("fx"))
                made[line["id"]] = line["speech"]
                remember()
                done += 1
                streak = 0
                log(f"[{done + failed}/{len(todo)}] {line['key']} {(args.out / (line['id'] + '.ogg')).stat().st_size // 1024} KB "
                    f"accounts {studio.accounts} {time.time() - begin:.0f}s  {line['speech'][:50]}")
            else:
                failed += 1
                streak += 1
                log(f"FAILED {line['key']} {line['id']}: {line['speech'][:60]}")
                if streak >= 4:
                    restarts += 1
                    if restarts > 3 or not studio.open():
                        log("too many failures in a row: stopping")
                        break
                    streak = 0
    except OutOfGems:
        failed += 1
    finally:
        studio.close()
        remember()
        count = write_manifest(args.out)
        log(f"done {done}, failed {failed}; {count} files in {args.out}; {time.time() - begin:.0f}s")
    if failed:
        sys.exit(1)


main()
