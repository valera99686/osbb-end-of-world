export interface EventEffect {
  coins?: number;
  scrap?: number;
  damageMax?: number;
  healMax?: number;
  rescue?: boolean;
  loot?: 'module' | 'furniture';
  rare?: boolean;
  // Something is lost: one module (fitted or spare) or one piece of furniture
  // of the house, picked from the seed.
  loseModule?: boolean;
  loseFurniture?: boolean;
}
export interface CampaignEvent {
  id: string;
  chapter: number;
  title: string;
  text: string;
  // A meeting for two players only (a raid with a partner): each takes one of
  // the two roles, and nothing happens until both have done their part. It has
  // one choice, the joint action, and no price.
  together?: { roles: [string, string] };
  choices: {
    label: string;
    detail: string;
    effect: EventEffect;
    result: string;
    // A gamble: with this chance the choice does what it says; otherwise
    // `fail` happens instead, and `result` is what is told. The roll comes
    // from the seed, so both ends and a reload see the same.
    risk?: { chance: number; fail: EventEffect; result: string };
  }[];
}
