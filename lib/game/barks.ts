export function perkOfferLine(
  owner: string,
  perk: PerkId,
  run: Pick<Run, 'level' | 'perks'>,
) {
  const lines = OFFER[owner];
  if (!lines?.length) return '';
  let hash = run.level * 31 + (run.perks?.length ?? 0) * 7;
  for (let i = 0; i < perk.length; i++)
    hash = (hash * 33 + perk.charCodeAt(i)) >>> 0;
  return lines[hash % lines.length];
}

