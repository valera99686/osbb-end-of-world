// A tiny deterministic hash, so a day or a run always picks the same line.
function pick<T>(items: readonly T[], seed: number): T {
  const n = Math.abs(Math.floor(Number.isFinite(seed) ? seed : 0));
  return items[n % items.length];
}
export function hashText(text: string): number {
  let h = 2166136261;
  for (let i = 0; i < text.length; i++) {
    h ^= text.charCodeAt(i);
    h = Math.imul(h, 16777619) >>> 0;
  }
  return h >>> 0;
}
// The notice of the day; `shift` steps through the board by hand.
export function noticeIndex(day: string, shift = 0): number {
  return (hashText(day) + Math.max(0, Math.floor(shift))) % NOTICES.length;
}
export function resultQuip(won: boolean, seed: number): string {
  return pick(won ? WIN_QUIPS : DEFEAT_QUIPS, seed);
}
export function tabTitle(seed: number): string {
  return pick(TAB_TITLES, seed);
}
