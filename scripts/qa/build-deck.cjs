function base(title, kicker) {
  const s = pptx.addSlide();
  n += 1;
  s.background = { color: C.bg };
  if (kicker)
    s.addText(kicker.toUpperCase(), {
      x: 0.6, y: 0.35, w: 8, h: 0.3,
      fontFace: FONT_B, fontSize: 11, color: C.teal, charSpacing: 3, margin: 0,
    });
  s.addText(title, {
    x: 0.6, y: 0.62, w: W - 1.2, h: 0.8,
    fontFace: FONT_B, fontSize: 30, color: C.text, margin: 0, valign: 'top',
  });
  s.addShape(pptx.ShapeType.rect, { x: 0.6, y: 1.42, w: 0.9, h: 0.05, fill: { color: C.amber }, line: { color: C.amber, width: 0 } });
  s.addText(String(n), {
    x: W - 1.0, y: H - 0.5, w: 0.5, h: 0.3,
    fontFace: FONT, fontSize: 10, color: C.muted, align: 'right', margin: 0,
  });
  s.addText('ОСББ кінця світу · 0.37.0', {
    x: 0.6, y: H - 0.5, w: 5, h: 0.3, fontFace: FONT, fontSize: 10, color: C.muted, margin: 0,
  });
  return s;
}
// A screenshot with a thin frame; the size keeps the picture's proportions.
function shot(s, file, x, y, w, ratio = 1280 / 800) {
  const h = w / ratio;
  s.addShape(pptx.ShapeType.rect, { x: x - 0.04, y: y - 0.04, w: w + 0.08, h: h + 0.08, fill: { color: C.panel }, line: { color: C.line, width: 1 } });
  s.addImage({ path: IMG(file), x, y, w, h });
  return h;
}
function caption(s, text, x, y, w) {
  s.addText(text, { x, y, w, h: 0.3, fontFace: FONT, fontSize: 11, color: C.muted, margin: 0, align: 'left' });
}
function bullets(s, items, x, y, w, h, size = 16) {
  s.addText(
    items.map((t) => ({ text: t, options: { bullet: { code: '25A0', indent: 18 }, breakLine: true, color: C.text } })),
    { x, y, w, h, fontFace: FONT, fontSize: size, color: C.text, valign: 'top', margin: 0, paraSpaceAfter: 9, lineSpacingMultiple: 1.05 },
  );
}
function card(s, x, y, w, h, head, body, accent = C.amber) {
  s.addShape(pptx.ShapeType.roundRect, { x, y, w, h, rectRadius: 0.08, fill: { color: C.panel }, line: { color: C.line, width: 1 } });
  s.addShape(pptx.ShapeType.rect, { x, y: y + 0.12, w: 0.06, h: h - 0.24, fill: { color: accent }, line: { color: accent, width: 0 } });
  s.addText(head, { x: x + 0.3, y: y + 0.18, w: w - 0.5, h: 0.45, fontFace: FONT_B, fontSize: 17, color: accent, margin: 0, valign: 'top' });
  s.addText(body, { x: x + 0.3, y: y + 0.7, w: w - 0.5, h: h - 0.85, fontFace: FONT, fontSize: 14, color: C.text, margin: 0, valign: 'top' });
}
function stat(s, x, y, w, big, small, color = C.amber) {
  s.addText(big, { x, y, w, h: 0.7, fontFace: FONT_B, fontSize: 34, color, margin: 0, align: 'left' });
  s.addText(small, { x, y: y + 0.72, w, h: 0.5, fontFace: FONT, fontSize: 12, color: C.muted, margin: 0, valign: 'top' });
}

