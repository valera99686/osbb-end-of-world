"""Voices the game's lines with OmniVoice (k2-fsa), locally on the graphics card.

Run it with the Python of the OmniVoice environment, after `npm test` and
`node scripts/voice/export-lines.cjs <lines.json>`:

    <omnivoice python> scripts/voice/generate.py --lines lines.json [--only mechanic,spark]
                                                  [--limit 5] [--force] [--refs-only]

Every speaker gets one reference clip designed from voices.json (kept in
--refs; scripts/voice/cast.py measures and picks them); each line is then spoken
by cloning that clip, so a character sounds the same in every line. voices.json
also sets a pace (`speed`) and a sound shape (`fx`, ffmpeg filters) per speaker. Output: public/voice/<id>.ogg (Opus, mono) and
lib/game/voice-manifest.ts (the ids that exist).
"""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
import time
import wave
from pathlib import Path

os.environ.setdefault("HF_HUB_OFFLINE", "1")

ROOT = Path(__file__).resolve().parents[2]
RATE = 24000
STEPS = 16
BITRATE = "20k"
# Per-speaker sound shaping after synthesis (ffmpeg audio filters).
EFFECTS = {
    # A speakerphone: narrow band, squeezed.
    "intercom": "highpass=f=320,lowpass=f=3300,acompressor=threshold=-20dB:ratio=5:attack=5:release=80,volume=1.3",
    # A building-sized system: a faint echo.
    "svitanok": "aecho=0.85:0.5:55|90:0.22|0.12",
}
TRIM = (
    "silenceremove=start_periods=1:start_threshold=-48dB:start_silence=0.04,"
    "areverse,silenceremove=start_periods=1:start_threshold=-48dB:start_silence=0.12,areverse"
)
LOUDNESS = "loudnorm=I=-18:TP=-1.5:LRA=9"
# Every voice loses a little of the top end (a first listener called the voices harsh): a gentle shelf above 4.5 kHz.
SOFTEN = "highshelf=f=4500:g=-3"


def log(message: str) -> None:
    print(message, flush=True)


def write_wav(path: Path, wave_data) -> float:
    import numpy as np

    pcm = (np.clip(np.asarray(wave_data, dtype=np.float32).reshape(-1), -1, 1) * 32767).astype("<i2")
    with wave.open(str(path), "wb") as out:
        out.setnchannels(1)
        out.setsampwidth(2)
        out.setframerate(RATE)
        out.writeframes(pcm.tobytes())
    return len(pcm) / RATE


def encode(source: Path, target: Path, key: str, effects: dict) -> None:
    chain = ",".join(part for part in (TRIM, effects.get(key), SOFTEN, LOUDNESS) if part)
    subprocess.run(
        ["ffmpeg", "-y", "-loglevel", "error", "-i", str(source), "-af", chain, "-ac", "1",
         "-c:a", "libopus", "-b:a", BITRATE, "-application", "voip", str(target)],
        check=True,
    )


def write_manifest(out_dir: Path) -> int:
    ids = sorted(path.stem for path in out_dir.glob("*.ogg"))
    body = ",\n  ".join(f"'{i}'" for i in ids)
    manifest = ROOT / "lib" / "game" / "voice-manifest.ts"
    manifest.write_text(
        "// Generated by scripts/voice/generate.py: the voiced lines that have a file in public/voice.\n"
        f"export const VOICE_IDS: ReadonlySet<string> = new Set([\n  {body},\n]);\n",
        encoding="utf-8",
    )
    return len(ids)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--lines", type=Path, required=True)
    parser.add_argument("--voices", type=Path, default=Path(__file__).with_name("voices.json"))
    parser.add_argument("--out", type=Path, default=ROOT / "public" / "voice")
    parser.add_argument("--refs", type=Path, default=ROOT / "scripts" / "voice" / "refs")
    parser.add_argument("--spoken", type=Path, default=Path(__file__).with_name("spoken.json"),
                        help="id -> the text each recording was made from; a changed text is spoken again")
    parser.add_argument("--work", type=Path, default=None, help="where the raw WAV files go")
    parser.add_argument("--only", default="", help="comma-separated speakers")
    parser.add_argument("--limit", type=int, default=0, help="at most this many lines per speaker")
    parser.add_argument("--force", action="store_true", help="speak lines again even if a file exists")
    parser.add_argument("--refs-only", action="store_true", help="only (re)create the reference clips")
    parser.add_argument("--reencode", action="store_true",
                        help="no synthesis: run the raw WAV files in --work through the filters again (after a change to fx or SOFTEN)")
    parser.add_argument("--keep-refs", action="store_true",
                        help="with --force: speak the lines again but keep the reference clips (cast.py picked them)")
    args = parser.parse_args()

    voices = json.loads(args.voices.read_text(encoding="utf-8"))
    lines = json.loads(args.lines.read_text(encoding="utf-8"))
    only = {k for k in args.only.split(",") if k}
    args.out.mkdir(parents=True, exist_ok=True)
    args.refs.mkdir(parents=True, exist_ok=True)
    work = args.work or (args.refs / "work")
    work.mkdir(parents=True, exist_ok=True)

    if args.reencode:
        effects = {**EFFECTS, **{k: c["fx"] for k, c in voices.items() if c.get("fx")}}
        count = 0
        for line in lines:
            raw = work / f"{line['id']}.wav"
            if (only and line["key"] not in only) or not raw.exists():
                continue
            encode(raw, args.out / f"{line['id']}.ogg", line["key"], effects)
            count += 1
        log(f"re-encoded {count} lines from {work}; {write_manifest(args.out)} files in {args.out}")
        return

    import torch
    from omnivoice import OmniVoice

    started = time.time()
    model = OmniVoice.from_pretrained("k2-fsa/OmniVoice", device_map="cuda:0", dtype=torch.float16)
    log(f"model ready in {time.time() - started:.0f}s")

    # voices.json can add a `fx` filter chain (ffmpeg) and a `speed` per speaker.
    effects = {**EFFECTS, **{k: c["fx"] for k, c in voices.items() if c.get("fx")}}
    pace = {k: {"speed": c["speed"]} if c.get("speed") else {} for k, c in voices.items()}
    refs: dict[str, tuple[Path, str]] = {}
    for key, cfg in voices.items():
        if only and key not in only:
            continue
        wav = args.refs / f"{key}.wav"
        if not wav.exists() or (args.force and not args.keep_refs):
            torch.manual_seed(cfg["seed"])
            audio = model.generate(text=cfg["refText"], language="Ukrainian", instruct=cfg["instruct"], num_step=STEPS, **pace[key])
            seconds = write_wav(wav, audio[0])
            log(f"ref {key}: {cfg['instruct']} -> {seconds:.1f}s")
        refs[key] = (wav, cfg["refText"])
    if args.refs_only:
        return

    made = json.loads(args.spoken.read_text(encoding="utf-8")) if args.spoken.exists() else {}
    done = skipped = failed = 0
    spoken = {key: 0 for key in refs}
    begin = time.time()
    for line in lines:
        key = line["key"]
        if key not in refs:
            continue
        if args.limit and spoken[key] >= args.limit:
            continue
        target = args.out / f"{line['id']}.ogg"
        spoken[key] += 1
        # A recording is current while the text it was made from is unchanged.
        if target.exists() and not args.force and made.get(line["id"]) == line["speech"]:
            skipped += 1
            continue
        ref_wav, ref_text = refs[key]
        try:
            torch.manual_seed(int(line["id"], 36) % (2**31))
            audio = model.generate(
                text=line["speech"], language="Ukrainian", ref_audio=str(ref_wav), ref_text=ref_text, num_step=STEPS,
                **pace[key])
            raw = work / f"{line['id']}.wav"
            seconds = write_wav(raw, audio[0])
            encode(raw, target, key, effects)
            made[line["id"]] = line["speech"]
            done += 1
            log(f"[{done + skipped + failed}/{len(lines)}] {key} {seconds:.1f}s {target.stat().st_size // 1024} KB  {line['speech'][:48]}")
        except Exception as exc:  # one bad line must not stop the batch
            failed += 1
            log(f"FAILED {key} {line['id']}: {type(exc).__name__}: {str(exc)[:160]}")
    live = {line["id"] for line in lines}
    made = {i: t for i, t in made.items() if i in live}
    args.spoken.write_text(json.dumps(made, ensure_ascii=False, indent=1, sort_keys=True) + "\n", encoding="utf-8")
    count = write_manifest(args.out)
    total = sum(p.stat().st_size for p in args.out.glob("*.ogg"))
    log(f"done {done}, kept {skipped}, failed {failed}; {count} files, {total / 1024 / 1024:.2f} MB; {time.time() - begin:.0f}s")
    if failed:
        sys.exit(1)


main()
