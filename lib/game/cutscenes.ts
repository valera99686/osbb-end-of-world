export const SCENE_BY_ID: Record<string, Cutscene> = Object.assign(
  Object.create(null),
  Object.fromEntries(CUTSCENES.map((s) => [s.id, s])),
);
export function sceneUnlocked(
  id: string,
  wins: number,
  chapter?: number,
): boolean {
  const s = SCENE_BY_ID[id];
  return (
    !!s &&
    (s.id === 'prologue' ||
      s.id === 'origins' ||
      (s.victory
        ? wins > 0 || (chapter !== undefined && chapter > s.chapter)
        : wins > 0 ||
          s.chapter === 0 ||
          (chapter !== undefined && chapter >= s.chapter)))
  );
}
export function restoreSceneProgress(
  raw: unknown,
  wins: number,
  chapter?: number,
): { id: string; index: number } | null {
  if (!raw || typeof raw !== 'object') return null;
  const r = raw as { id: string; index: number };
  return sceneUnlocked(r.id, wins, chapter) && Number.isInteger(r.index)
    ? {
        id: r.id,
        index: Math.max(
          0,
          Math.min(SCENE_BY_ID[r.id].shots.length - 1, r.index),
        ),
      }
    : null;
}
