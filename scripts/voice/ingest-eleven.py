"""Turns raw MP3 files made by a batch voice tool into the game's voice-over.

The tool writes one MP3 per line, named by the line id, into scripts/voice/refs/eleven/.
This script checks that each file holds the words of its line, runs the good ones through
the same filters as eleven.py (trim, the speaker's `fx`, loudness), writes
public/voice/<id>.ogg, remembers the text in spoken-eleven.json and rewrites
lib/game/voice-manifest.ts. A file that fails the check is left alone and listed, so the
tool can speak it again.

The check listens with faster-whisper (pip install faster-whisper); run the script with a
Python that has it, or pass --no-check to take every file as it is:

    python scripts/voice/ingest-eleven.py [--only boris,nina] [--min-score 0.6] [--no-check]
        [--report scripts/voice/refs/ingest-report.json]
"""
from __future__ import annotations

import argparse
import difflib
import json
import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
BITRATE = "24k"
TRIM = (
    "silenceremove=start_periods=1:start_threshold=-48dB:start_silence=0.04,"
    "areverse,silenceremove=start_periods=1:start_threshold=-48dB:start_silence=0.12,areverse"
)
LOUDNESS = "loudnorm=I=-18:TP=-1.5:LRA=9"
TAG = re.compile(r"\[[^\]]*\]")
# Characters a second of this kind of speech holds; far outside it means a cut or a stall.
# A short line or one with a sigh or a pause tag may well be slow, so only the top is strict there.
CPS_RANGE = (5.0, 30.0)
SHORT_LINE = 24
# A tagged line may carry a laugh or a sigh the listener turns into extra words.
TAGGED_SLACK = 0.1


def log(message: str) -> None:
    print(message, flush=True)


def words(text: str) -> str:
    text = TAG.sub(" ", text).lower().replace("ё", "е").replace("’", "'").replace("ʼ", "'")
    return " ".join(re.findall(r"[\w']+", text))


def duration(path: Path) -> float:
    out = subprocess.run(
        ["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", str(path)],
        capture_output=True, text=True,
    ).stdout.strip()
    try:
        return float(out)
    except ValueError:
        return 0.0


def encode(source: Path, target: Path, fx: str | None) -> None:
    chain = ",".join(part for part in (TRIM, fx, LOUDNESS) if part)
    temp = target.with_suffix(".tmp.ogg")
    subprocess.run(
        ["ffmpeg", "-y", "-loglevel", "error", "-i", str(source), "-af", chain, "-ac", "1",
         "-c:a", "libopus", "-b:a", BITRATE, "-application", "voip", str(temp)],
        check=True,
    )
    os.replace(temp, target)


def write_manifest(out_dir: Path) -> int:
    ids = sorted(path.stem for path in out_dir.glob("*.ogg") if not path.stem.endswith(".tmp"))
    body = ",\n  ".join(f"'{i}'" for i in ids)
    manifest = ROOT / "lib" / "game" / "voice-manifest.ts"
    manifest.write_text(
        "// Generated by scripts/voice/generate.py or eleven.py: the voiced lines that have a file in public/voice.\n"
        f"export const VOICE_IDS: ReadonlySet<string> = new Set([\n  {body},\n]);\n",
        encoding="utf-8",
    )
    return len(ids)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--lines", type=Path, default=HERE / "lines-eleven.json")
    parser.add_argument("--voices", type=Path, default=HERE / "eleven-voices.json")
    parser.add_argument("--work", type=Path, default=HERE / "refs" / "eleven")
    parser.add_argument("--out", type=Path, default=ROOT / "public" / "voice")
    parser.add_argument("--spoken", type=Path, default=HERE / "spoken-eleven.json")
    parser.add_argument("--report", type=Path, default=HERE / "refs" / "ingest-report.json")
    parser.add_argument("--only", default="", help="comma-separated speakers")
    parser.add_argument("--min-score", type=float, default=0.6, help="least similarity of the heard words to the line")
    parser.add_argument("--accept", default="", help="comma-separated line ids to take although the check fails "
                        "(listened to by hand: a hum, a number the ear writes in digits)")
    parser.add_argument("--no-check", action="store_true", help="take every file as it is")
    parser.add_argument("--force", action="store_true", help="also files of lines that are already recorded")
    args = parser.parse_args()

    voices = json.loads(args.voices.read_text(encoding="utf-8"))
    lines = json.loads(args.lines.read_text(encoding="utf-8"))
    only = {k for k in args.only.split(",") if k}
    accepted = {k for k in args.accept.split(",") if k}
    made =json.loads(args.spoken.read_text(encoding="utf-8")) if args.spoken.exists() else {}
    args.out.mkdir(parents=True, exist_ok=True)

    todo = [
        line for line in lines
        if line["key"] in voices and (not only or line["key"] in only)
        and (args.work / f"{line['id']}.mp3").exists()
        and (args.force or made.get(line["id"]) != line["speech"])
    ]
    log(f"{len(todo)} files to take of {len(lines)} lines")

    model = None
    if not args.no_check and todo:
        try:
            from faster_whisper import WhisperModel
        except ImportError:
            sys.exit("faster-whisper is not installed here: pip install faster-whisper, or pass --no-check")
        model = WhisperModel("small", device="cpu", compute_type="int8")

    report, taken = [], 0
    for index, line in enumerate(todo, 1):
        raw = args.work / f"{line['id']}.mp3"
        seconds = duration(raw)
        expected = words(line["speech"])
        cps = len(expected) / seconds if seconds else 0.0
        tagged = bool(TAG.search(line["speech"]))
        score, heard, problem = 1.0, "", ""
        if not seconds:
            problem = "empty or unreadable file"
        elif cps > CPS_RANGE[1] or (cps < CPS_RANGE[0] and not tagged and len(expected) > SHORT_LINE):
            problem = f"{cps:.1f} characters a second"
        if seconds and problem and line["id"] in accepted:
            problem = ""
        if not problem and model:
            segments, _ = model.transcribe(str(raw), language="uk", beam_size=5)
            heard = words(" ".join(s.text for s in segments))
            score = difflib.SequenceMatcher(None, expected, heard).ratio()
            if score < args.min_score - (TAGGED_SLACK if tagged else 0) and line["id"] not in accepted:
                problem = f"heard «{heard[:70]}» (score {score:.2f})"
        entry = {"id": line["id"], "key": line["key"], "score": round(score, 3), "seconds": round(seconds, 2),
                 "tagged": tagged, "ok": not problem, "problem": problem, "heard": heard}
        report.append(entry)
        if problem:
            log(f"[{index}/{len(todo)}] BAD {line['key']} {line['id']}: {problem}")
            continue
        encode(raw, args.out / f"{line['id']}.ogg", voices[line["key"]].get("fx"))
        made[line["id"]] = line["speech"]
        taken += 1
        if taken % 25 == 0:
            args.spoken.write_text(json.dumps(made, ensure_ascii=False, indent=1, sort_keys=True) + "\n", encoding="utf-8")
            log(f"[{index}/{len(todo)}] {taken} taken")

    args.spoken.write_text(json.dumps(made, ensure_ascii=False, indent=1, sort_keys=True) + "\n", encoding="utf-8")
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(json.dumps(report, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    count = write_manifest(args.out)
    bad = [e for e in report if not e["ok"]]
    log(f"taken {taken}, bad {len(bad)}; {count} files in {args.out}")
    if bad:
        log("to speak again: " + ", ".join(e["id"] for e in bad))
        sys.exit(1)


main()
