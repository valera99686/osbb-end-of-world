export function loreForProgress(
  existing: readonly string[],
  wins: number,
  visitedChapter?: number,
): string[] {
  return LORE.filter(
    (entry) =>
      existing.includes(entry.id) ||
      entry.unlock === 'start' ||
      (entry.unlock === 'win' && wins > entry.chapter) ||
      (entry.unlock === 'visit' &&
        (wins > entry.chapter ||
          (visitedChapter !== undefined && visitedChapter >= entry.chapter))),
  ).map((e) => e.id);
}
